export const MARINA_SPOTS = [...NORTE, ...SUR];
const CAR_L = 4.6, STALL = 2.5, RAYA = 0xe9e7e0;

/** antes de levantar la ciudad: las plazas, para que parked.js aparque coches en ellas */
export function tuneAparcamientosMarina(map) {
  map.lotSpots?.push(...MARINA_SPOTS);
  map.aparcamientosMarina = true;
}

/** se monta con lo demás de Valterra, en su primera fase: las rayas de las plazas */
export function buildAparcamientosMarina(scene, map) {
  if (!map?.aparcamientosMarina) return null;
  const k = new Kit();
  for (const [x, z, h] of MARINA_SPOTS) {
    const fx = Math.sin(h), fz = Math.cos(h), sx = fz, sz = -fx;
    // las dos rayas de los lados de la plaza y la del fondo
    for (const s of [-1, 1]) k.box(x + sx * s * STALL / 2, 0.1, z + sz * s * STALL / 2, 0.1, 0.012, CAR_L + 0.3, RAYA, { ry: h, list: k.shell });
    k.box(x - fx * (CAR_L / 2 + 0.15), 0.1, z - fz * (CAR_L / 2 + 0.15), STALL, 0.012, 0.1, RAYA, { ry: h, list: k.shell });
  }
  const { group } = k.build('aparcamientosMarina');
  scene.add(group);
  return { group };
}
